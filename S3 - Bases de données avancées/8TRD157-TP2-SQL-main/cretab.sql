-- b. Assignation d’un directeur.
CREATE OR REPLACE PROCEDURE ASSIGNER_DIRECTEUR_DEPARTEMENT(
    p_id_departement IN NUMBER,
    p_id_directeur IN NUMBER
)
    IS
    v_departement_count NUMBER;
BEGIN
    -- Vérifier si le département existe
    SELECT COUNT(*)
    INTO v_departement_count
    FROM DEPARTEMENT
    WHERE ID_DEPARTEMENT = p_id_departement;

    IF v_departement_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Le département spécifié n''existe pas.');
    END IF;

    -- Mise à jour du directeur dans le département
    UPDATE DEPARTEMENT
    SET ID_DIRECTEUR = p_id_directeur
    WHERE ID_DEPARTEMENT = p_id_departement;

    COMMIT;
END;
