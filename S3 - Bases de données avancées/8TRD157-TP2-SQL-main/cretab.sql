            SELECT ID_PERSONNE INTO id_personne FROM PERSONNE WHERE NAS = new_nas;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                id_personne := NULL;
        END;
        -- Si aucune personne n'a ce NAS, on crée une nouvelle personne
        IF id_personne IS NULL THEN
            INSERT INTO PERSONNE (NOM, PRENOM, NAS, DATE_NAISSANCE, COURRIEL_PERSONNEL, NUMERO_TELEPHONE)
            VALUES (new_nom, new_prenom, new_nas, TO_DATE(new_date_naissance, 'YYYY-MM-DD'), new_courriel_personnel,
                    new_numero_telephone)
            RETURNING ID_PERSONNE INTO id_personne;
            -- Si non, on vérifie si la personne est déjà un étudiant
        ELSE
            BEGIN
                -- Compte le nombre d'étudiants qui possèdent le même id de personne
                SELECT COUNT(*) INTO nombre_etudiant_avec_meme_personne FROM ETUDIANT WHERE ID_PERSONNE = id_personne;
                -- Si le nombre est supérieur à 0, on lève une exception, car l'étudiant existe déjà
                IF nombre_etudiant_avec_meme_personne > 0 THEN
                    RAISE_APPLICATION_ERROR(-20001, 'Cet étudiant existe déjà dans la base de données.');
                END IF;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    id_etudiant := NULL;
            END;
        END IF;

        -- Création du courriel scolaire

        -- Compte le nombre d'étudiants qui possèdent le même nom et prénom
        SELECT COUNT(*)
        INTO nombre_etudiant_avec_meme_nom_prenom
        FROM ETUDIANT
                 JOIN PERSONNE ON ETUDIANT.ID_PERSONNE = PERSONNE.ID_PERSONNE
        WHERE PERSONNE.NOM = new_nom
          AND PERSONNE.PRENOM = new_prenom;

        -- Construction du courriel scolaire
        courriel_scolaire := LOWER(new_prenom) || '.' || LOWER(new_nom) || TO_CHAR(nombre_etudiant_avec_meme_nom_prenom + 1, 'FM000') || '@uqac.ca';

        -- Création du code permanent

        -- Initialisation du générateur de nombres aléatoires
        DBMS_RANDOM.INITIALIZE(TO_NUMBER(TO_CHAR(SYSDATE, 'SSSSS')));

        -- Construction du code permanent
        code_permament := LOWER(SUBSTR(new_nom, 1, 3)) || LOWER(SUBSTR(new_prenom, 1, 1)) || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000000, 99999999)));

        -- Création du nouvel étudiant
        INSERT INTO ETUDIANT (ID_DEPARTEMENT, ID_PERSONNE, CODE_STATUT, CODE_PERMANENT, COURRIEL_SCOLAIRE)
        VALUES (new_id_departement, id_personne, new_status_etudiant, code_permament, courriel_scolaire);

        -- Commit les changements dans la BD
        COMMIT;
    END;
END;
