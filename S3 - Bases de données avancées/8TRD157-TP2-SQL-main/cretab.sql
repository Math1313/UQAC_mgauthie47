-- a. Connaître la liste des cours auxquels peut s’inscrire un étudiant.
CREATE OR REPLACE VIEW VUE_COURS_DISPONIBLES AS
SELECT CE.ID_COURS_ENSEIGNE,
	   C.TITRE, 
	   C.SIGLE, 
	   CE.CODE_LOCAL, 
	   C.CREDIT, 
       C.NOMBRE_HEURE_COURS, 
	   C.NOMBRE_HEURE_LABORATOIRE, 
	   E.ID_ETUDIANT, 
	   S.ID_SESSION_
FROM COURS_ENSEIGNE CE
JOIN COURS C ON CE.ID_COURS = C.ID_COURS
JOIN ETUDIANT E ON E.ID_DEPARTEMENT = C.ID_DEPARTEMENT
JOIN SESSION_ S ON CE.ID_SESSION_ = S.ID_SESSION_;

-- b. Connaître la liste des cours suivi pour une session.
CREATE OR REPLACE VIEW VUE_COURS_INSCRITS_ETUDIANT AS
SELECT ECE.ID_ETUDIANT_COURS_ENSEIGNE,
       E.ID_ETUDIANT,
       E.ID_DEPARTEMENT,
       C.TITRE,
       C.SIGLE,
       CE.CODE_LOCAL,
       C.CREDIT,
       C.NOMBRE_HEURE_COURS,
       C.NOMBRE_HEURE_LABORATOIRE,
       S.ID_SESSION_,
       ECE.CODE_STATUT,
       ECE.NOTE_TOTALE
FROM ETUDIANT_COURS_ENSEIGNE ECE
JOIN COURS_ENSEIGNE CE ON ECE.ID_COURS_ENSEIGNE = CE.ID_COURS_ENSEIGNE
JOIN COURS C ON CE.ID_COURS = C.ID_COURS
JOIN ETUDIANT E ON ECE.ID_ETUDIANT = E.ID_ETUDIANT
JOIN SESSION_ S ON CE.ID_SESSION_ = S.ID_SESSION_;

-- c. Faire un bulletin des étudiants.
CREATE OR REPLACE VIEW VUE_BULLETIN_ETUDIANT AS
SELECT E.ID_ETUDIANT,
       E.CODE_PERMANENT,
       P.NOM,
       P.PRENOM,
       AVG(ECE.NOTE_TOTALE) AS MOYENNE_GENERALE,  -- Calcul de la moyenne pour l'étudiant
       LISTAGG(C.TITRE, ', ') WITHIN GROUP (ORDER BY C.TITRE) AS COURS,  -- Concaténation des titres de cours
       COUNT(*) AS NOMBRE_DE_COURS  -- Compte le nombre de cours inscrits
FROM ETUDIANT_COURS_ENSEIGNE ECE
         JOIN ETUDIANT E ON ECE.ID_ETUDIANT = E.ID_ETUDIANT
         JOIN PERSONNE P ON E.ID_PERSONNE = P.ID_PERSONNE
         JOIN COURS_ENSEIGNE CE ON ECE.ID_COURS_ENSEIGNE = CE.ID_COURS_ENSEIGNE
         JOIN COURS C ON CE.ID_COURS = C.ID_COURS
WHERE ECE.NOTE_TOTALE IS NOT NULL
GROUP BY E.ID_ETUDIANT, E.CODE_PERMANENT, P.NOM, P.PRENOM  -- Regroupement par étudiant
ORDER BY E.ID_ETUDIANT;

-- d. Obtenir une liste d'encienneté des enseignants
CREATE OR REPLACE VIEW VUE_ANTIENNETE_ENSEIGNANTS AS
SELECT P.NOM,
       P.PRENOM,
       E.CODE_STATUT,
       E.DATE_EMBAUCHE,
       E.COURRIEL_PROFESSIONNEL,
       ROUND(MONTHS_BETWEEN(SYSDATE, E.DATE_EMBAUCHE) / 12, 1) AS ANNEES_ANCIENNETE
FROM ENSEIGNANT E
         JOIN PERSONNE P ON E.ID_PERSONNE = P.ID_PERSONNE
WHERE E.CODE_STATUT != 0 -- Retirer les enseignants non actifs
ORDER BY E.DATE_EMBAUCHE;