-- b. Assignation de préalables. 
CREATE OR REPLACE PROCEDURE AJOUTER_PREALABLE(
    p_id_cours IN NUMBER,
    p_id_cours_prealable IN NUMBER
)
    IS
BEGIN
    -- Vérifier si le cours existe
    DECLARE
        v_cours_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_cours_count
        FROM COURS
        WHERE ID_COURS = p_id_cours;

        IF v_cours_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Le cours spécifié n''existe pas.');
        END IF;
    END;

    -- Vérifier si le cours préalable existe
    DECLARE
        v_prealable_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_prealable_count
        FROM COURS
        WHERE ID_COURS = p_id_cours_prealable;

        IF v_prealable_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Le cours préalable spécifié n''existe pas.');
        END IF;
    END;

    -- Ajouter le préalable au cours
    INSERT INTO PREALABLE (ID_COURS,
                           ID_COURS_PREALABLE)
    VALUES (p_id_cours,
            p_id_cours_prealable);

    COMMIT;
END;
/

-- c. Modification cours. 
CREATE OR REPLACE PROCEDURE MODIFIER_COURS(
    p_id_cours IN NUMBER,
    p_id_enseignant IN NUMBER DEFAULT NULL,
    p_id_departement IN NUMBER DEFAULT NULL,
    p_titre IN VARCHAR2 DEFAULT NULL,
    p_sigle IN VARCHAR2 DEFAULT NULL,
    p_description IN VARCHAR2 DEFAULT NULL,
    p_lien_site_web IN VARCHAR2 DEFAULT NULL,
    p_credit IN NUMBER DEFAULT NULL,
    p_nombre_heure_cours IN NUMBER DEFAULT NULL,
    p_nombre_heure_laboratoire IN NUMBER DEFAULT NULL,
    p_nombre_heure_travail IN NUMBER DEFAULT NULL
)
    IS
BEGIN
    -- Mise à jour des informations du cours
    UPDATE COURS
    SET ID_ENSEIGNANT            = COALESCE(p_id_enseignant, ID_ENSEIGNANT),
        ID_DEPARTEMENT           = COALESCE(p_id_departement, ID_DEPARTEMENT),
        TITRE                    = COALESCE(p_titre, TITRE),
        SIGLE                    = COALESCE(p_sigle, SIGLE),
        DESCRIPTION              = COALESCE(p_description, DESCRIPTION),
        LIEN_SITE_WEB            = COALESCE(p_lien_site_web, LIEN_SITE_WEB),
        CREDIT                   = COALESCE(p_credit, CREDIT),
        NOMBRE_HEURE_COURS       = COALESCE(p_nombre_heure_cours, NOMBRE_HEURE_COURS),
        NOMBRE_HEURE_LABORATOIRE = COALESCE(p_nombre_heure_laboratoire, NOMBRE_HEURE_LABORATOIRE),
        NOMBRE_HEURE_TRAVAIL     = COALESCE(p_nombre_heure_travail, NOMBRE_HEURE_TRAVAIL)
    WHERE ID_COURS = p_id_cours;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Le cours spécifié n''existe pas.');
    END IF;

    COMMIT;
END;
/

-- d. Modification préalables
CREATE OR REPLACE PROCEDURE MODIFIER_PREALABLE(
    p_id_prealable IN NUMBER,
    p_id_cours IN NUMBER DEFAULT NULL,
    p_id_cours_prealable IN NUMBER DEFAULT NULL
)
    IS
BEGIN
    -- Mise à jour des informations du préalable
    UPDATE PREALABLE
    SET ID_COURS           = COALESCE(p_id_cours, ID_COURS),
        ID_COURS_PREALABLE = COALESCE(p_id_cours_prealable, ID_COURS_PREALABLE)
    WHERE ID_PREALABLE = p_id_prealable;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Le préalable spécifié n''existe pas.');
    END IF;

    COMMIT;
END;
