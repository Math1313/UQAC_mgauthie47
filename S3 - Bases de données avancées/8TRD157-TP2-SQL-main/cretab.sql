CREATE OR REPLACE TRIGGER TRIGGER_VERIFIER_DIRECTEUR_EST_DANS_DEPARTEMENT
    BEFORE INSERT OR UPDATE
    ON DEPARTEMENT
    FOR EACH ROW
DECLARE
    v_id_departement_enseignant NUMBER;
BEGIN
    IF :NEW.ID_DIRECTEUR IS NOT NULL THEN
        -- Récupérer l'ID du département de l'enseignant
        SELECT ID_DEPARTEMENT
        INTO v_id_departement_enseignant
        FROM ENSEIGNANT
        WHERE ID_ENSEIGNANT = :NEW.ID_DIRECTEUR;

        -- Vérifier que l'enseignant est dans le même département que le département mis à jour
        IF v_id_departement_enseignant != :NEW.ID_DEPARTEMENT THEN
            RAISE_APPLICATION_ERROR(-20001, 'Le directeur doit être un enseignant dans le même département que celui-ci.');
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRIGGER_VERIFIER_DIRECTEUR_EXISTE_DEPARTEMENT
    BEFORE INSERT OR UPDATE
    ON COURS
    FOR EACH ROW
DECLARE
    v_directeur NUMBER;
BEGIN
    -- Vérifie si le département associé au cours a un directeur
    SELECT ID_DIRECTEUR
    INTO v_directeur
    FROM DEPARTEMENT
    WHERE ID_DEPARTEMENT = :NEW.ID_DEPARTEMENT;

    IF v_directeur IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Le département doit avoir un directeur avant d''assigner un cours.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRIGGER_VERIFIER_MEME_DEPARTEMENT_COURS_ENSEIGNANT
    BEFORE INSERT OR UPDATE
    ON COURS
    FOR EACH ROW
DECLARE
    v_id_departement_enseignant NUMBER;
BEGIN
    -- Vérifier si ID_ENSEIGNANT est NULL
    IF :NEW.ID_ENSEIGNANT IS NOT NULL THEN
        -- Récupérer l'ID du département de l'enseignant
        SELECT ID_DEPARTEMENT
        INTO v_id_departement_enseignant
        FROM ENSEIGNANT
        WHERE ID_ENSEIGNANT = :NEW.ID_ENSEIGNANT;

        -- Vérifier que l'enseignant est dans le même département que le cours
        IF v_id_departement_enseignant != :NEW.ID_DEPARTEMENT THEN
            RAISE_APPLICATION_ERROR(-20001, 'L''enseignant doit être dans le même département que le cours.');
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRIGGER_VERIFIER_MEME_DEPARTEMENT_COURS_ENSEIGNE_ENSEIGNANT
    BEFORE INSERT OR UPDATE
    ON COURS_ENSEIGNE
    FOR EACH ROW
DECLARE
    v_id_departement_enseignant NUMBER;
    v_id_departement_cours      NUMBER;
BEGIN
    -- Récupérer l'ID du département de l'enseignant
    SELECT ID_DEPARTEMENT
    INTO v_id_departement_enseignant
    FROM ENSEIGNANT
    WHERE ID_ENSEIGNANT = :NEW.ID_ENSEIGNANT;
    
    -- Récuperer l'ID du département auquel le cours appartient
    SELECT ID_DEPARTEMENT
    INTO v_id_departement_cours
    FROM COURS
    WHERE ID_COURS = :NEW.ID_COURS;
    
    -- Vérifier que l'enseignant est dans le même département que le cours
    IF v_id_departement_enseignant != v_id_departement_cours THEN
        RAISE_APPLICATION_ERROR(-20001, 'L''enseignant doit être dans le même département que le cours.');
    END IF;
END;
